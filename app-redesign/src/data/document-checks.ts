import type { DocType } from "@/lib/zip042";

/**
 * 서류별 "무엇을 조회하나요" 내용.
 *
 * ## 왜 데이터로 빼는가
 *
 * 같은 문구가 두 화면에 나옵니다 — `/analyze`(등기부)와 `/analyze/documents`(추가 서류 4종).
 * 화면마다 적어두면 한쪽만 고쳐지고 두 화면이 서로 다른 말을 하게 됩니다.
 * 이 서비스에서 "무엇을 확인하는지"는 사용자가 서류를 떼러 갈지 말지를 정하는
 * 근거라, 화면마다 다르면 신뢰를 잃습니다.
 *
 * 원본은 `docs/서류별_확인항목.md` 입니다(같은 내용의 PDF 도 나란히 두었습니다).
 * 문구를 고칠 때는 그 파일도 함께 고치세요.
 *
 * `docType` 은 백엔드가 받는 값과 정확히 같아야 합니다. 확정일자 부여현황은
 * 백엔드에 전용 종류가 없어 `other` 로 보냅니다 — 없는 종류를 지어내면 400 입니다.
 */
export interface DocumentCheck {
  id: string;
  docType: DocType;
  /** 카드 제목 */
  title: string;
  /** 접힌 상태에서 한 줄로 보이는 이유 */
  why: string;
  /** 펼쳤을 때 나오는 확인 항목 */
  checks: string[];
  /** "이 서류가 잡아내는 것" — 왜 떼어야 하는지를 한 문단으로 */
  catches: string;
  /** 발급·열람에 조건이 있는 서류만 */
  constraint?: string;
  /** 발급처 링크 */
  link?: { label: string; href: string };
  /**
   * 아직 자동 판독하지 않는 서류.
   *
   * 백엔드 `ensureExtractions` 가 `building_ledger` · `other` 를 건너뜁니다.
   * 올려두면 보관은 되지만 판정에는 반영되지 않습니다. 화면이 "확인합니다"라고
   * 말해 놓고 실제로 안 보면 거짓말이 되므로, 여기서 사실대로 표시합니다.
   * 판독을 붙이면 이 플래그를 지우세요.
   */
  manualOnly?: boolean;
}

